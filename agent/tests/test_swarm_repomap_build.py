def test_large_repo_is_fast_and_truncates_safely():
    files = {}
    for i in range(2000):
        pkg = f"pkg{i % 40}"
        files[f"{pkg}/mod{i}.py"] = f"from .mod{(i + 1) if (i + 1) % 50 else i - 1} import f{i}x\n\ndef f{i}(a):\n    if a:\n        return a\n    return {i}\n" if False else \
            f"def f{i}(a):\n    if a:\n        return a\n    return {i}\n\nclass C{i}:\n    def m(self):\n        return {i}\n"
        if i % 10 == 0:
            files[f"tests/test_mod{i}.py"] = f"from {pkg}.mod{i} import f{i}\n\ndef test_x():\n    assert f{i}(1)\n"
    t0 = time.monotonic()
    rm = build_repo_map(files)
    elapsed = time.monotonic() - t0
    assert elapsed < 5, elapsed
    assert rm.total_files == len(files) and len(rm.symbols) >= 2000 and not rm.truncated
    assert len(rm.render(4000)) <= 4000 and len(rm.slice_for(["pkg0/mod0.py"], 1000)) <= 1050
    capped = build_repo_map(files, max_files=500)
    assert capped.truncated and len(capped.files) == 500 and capped.skipped["cap"] > 0
    assert "TRUNCATED" in capped.render(2000)
    assert rm.tests_for(["pkg0/mod0.py"]) == ["tests/test_mod0.py"]


