def names(rm, path):
    return {s.name for s in rm.symbols_in(path)}


def test_python_map_symbols_commands_entrypoints_and_skips():
    rm = build_repo_map(PY)
    assert rm.primary_language == "python"
    assert rm.commands["test"].startswith("python -m pytest") and rm.commands["lint"] == "python -m ruff check ."
    assert names(rm, "pkg/core.py") >= {"run", "Runner", "Runner.go", "LIMIT"}
    sig = next(s for s in rm.symbols_in("pkg/core.py") if s.name == "run")
    assert sig.signature == "run(x, *, flag=False) -> int" and sig.exported
    priv = next(s for s in rm.symbols_in("pkg/core.py") if s.name == "Runner._private")
    assert not priv.exported
    assert "pkg/__main__.py" in rm.entrypoints and "scripts/tool.py" in rm.entrypoints
    # vendor / generated / binary / lock files are skipped and counted
    assert "node_modules/leftpad/index.js" not in rm.files and "gen/api_pb2.py" not in rm.files
    assert rm.skipped["vendor"] >= 1 and rm.skipped["generated"] >= 1 and rm.skipped["binary"] == 1 and rm.skipped["lock"] == 1
    assert rm.languages["python"] > 0 and not rm.truncated


def test_python_import_graph_cycles_tests_and_metrics():
    rm = build_repo_map(PY)
    assert rm.import_graph["pkg/core.py"] == ["pkg/util.py", "pkg/models.py"] or set(rm.import_graph["pkg/core.py"]) == {"pkg/util.py", "pkg/models.py"}
    assert rm.cycles and set(rm.cycles[0]) >= {"pkg/core.py", "pkg/util.py"}
    assert rm.test_map["tests/test_core.py"] == ["pkg/core.py"]
    assert rm.tests_for(["pkg/models.py"]) == ["tests/test_models.py"]
    assert rm.tests_for(["scripts/tool.py"]) == []
    run_metric = next(m for m in rm.files["pkg/core.py"].functions if m.name == "run")
    assert run_metric.complexity == 5  # 1 + if + (and) + for + inner if
    assert rm.metrics("pkg/core.py")["max_complexity"] == 5
    assert rm.importers_of("pkg/core.py")


def test_py_complexity_counts_branches_boolops_and_comprehensions():
    import ast
    fn = ast.parse("def f(a, b):\n    x = [i for i in a if i]\n    return b if a and b or x else 0\n").body[0]
    assert py_complexity(fn) == 1 + (1 + 1) + 1 + 2  # comprehension+if, ifexp, and/or (2 operators)


