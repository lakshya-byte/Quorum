def test_find_cycles_scc():
    g = {"a": ["b"], "b": ["c"], "c": ["a"], "d": ["a"], "e": ["e"], "f": []}
    cyc = find_cycles(g)
    comps = [set(c) for c in cyc]
    assert {"a", "b", "c"} in comps and {"e"} in comps and not any("d" in c or "f" in c for c in comps)


