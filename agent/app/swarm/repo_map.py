@dataclass
class Symbol:
    name: str
    kind: str  # function|class|method|const|type|interface|enum|component
    path: str
    line: int
    signature: str = ""
    exported: bool = True


@dataclass
class FuncMetric:
    name: str
    line: int
    lines: int
    complexity: int


@dataclass
class FileInfo:
    path: str
    lang: str
    lines: int
    size: int
    is_test: bool = False
    generated: bool = False
    parsed: bool = False
    functions: list[FuncMetric] = field(default_factory=list)
    imports_raw: list[str] = field(default_factory=list)


@dataclass
class RepoMap:
    files: dict[str, FileInfo] = field(default_factory=dict)
    languages: dict[str, int] = field(default_factory=dict)  # lang -> lines
    commands: dict[str, str] = field(default_factory=dict)  # install|build|test|lint|typecheck|dev
    frameworks: list[str] = field(default_factory=list)
    entrypoints: list[str] = field(default_factory=list)
    tests: list[str] = field(default_factory=list)
    test_map: dict[str, list[str]] = field(default_factory=dict)  # test path -> source paths it covers
    symbols: list[Symbol] = field(default_factory=list)
    import_graph: dict[str, list[str]] = field(default_factory=dict)  # path -> internal paths it imports
    cycles: list[list[str]] = field(default_factory=list)
    skipped: dict[str, int] = field(default_factory=dict)  # vendor|binary|generated|lock|oversize|cap
    truncated: bool = False
    total_files: int = 0
    primary_language: str = "unknown"
    tree_summary: str = ""
    _by_path: dict[str, list[Symbol]] = field(default_factory=dict, repr=False)
    _importers: dict[str, list[str]] = field(default_factory=dict, repr=False)

    # ---- queries -------------------------------------------------------------------------------------
    def symbols_in(self, path: str) -> list[Symbol]:
        return self._by_path.get(path, [])

    def importers_of(self, path: str) -> list[str]:
        return self._importers.get(path, [])

    def find_symbols(self, query: str, limit: int = 30) -> list[Symbol]:
        q = query.lower()
        scored = []
        for s in self.symbols:
            n = s.name.lower()
            if n == q:
                scored.append((0, s))
            elif n.startswith(q):
                scored.append((1, s))
            elif q in n or q in s.path.lower():
                scored.append((2, s))
        scored.sort(key=lambda t: (t[0], t[1].path, t[1].line))
        return [s for _, s in scored[:limit]]

    def tests_for(self, paths: list[str]) -> list[str]:
        """Test-impact selection: tests that map to any of `paths` (or that are themselves in `paths`)."""
        want = set(paths)
        out = [t for t, srcs in self.test_map.items() if want & set(srcs) or t in want]
        return sorted(set(out))

    def hotspots(self, n: int = 8) -> dict[str, list[tuple[str, int]]]:
        big_files = sorted(((p, f.lines) for p, f in self.files.items() if f.lang in CODE_LANGS and not f.is_test),
                           key=lambda t: -t[1])[:n]
        funcs = sorted(((f"{p}:{m.name}", m.complexity) for p, f in self.files.items() if not f.is_test
                        for m in f.functions), key=lambda t: -t[1])[:n]
        long_funcs = sorted(((f"{p}:{m.name}", m.lines) for p, f in self.files.items() if not f.is_test
                             for m in f.functions), key=lambda t: -t[1])[:n]
        return {"largest_files": big_files, "most_complex_functions": funcs, "longest_functions": long_funcs}

    def metrics(self, path: str) -> dict[str, Any]:
        f = self.files.get(path)
        if not f:
            return {}
        return {"lines": f.lines, "functions": len(f.functions),
                "max_complexity": max((m.complexity for m in f.functions), default=0),
                "max_function_lines": max((m.lines for m in f.functions), default=0)}

    def to_dict(self) -> dict[str, Any]:
        return {
            "files": self.total_files, "languages": self.languages, "primary_language": self.primary_language,
            "commands": self.commands, "frameworks": self.frameworks, "entrypoints": self.entrypoints,
            "tests": len(self.tests), "symbols": len(self.symbols), "cycles": self.cycles[:10],
            "truncated": self.truncated, "skipped": self.skipped,
        }

    # ---- rendering -----------------------------------------------------------------------------------
    def render(self, max_chars: int = 6000) -> str:
        sections: list[str] = []
        langs = ", ".join(f"{k} {v}" for k, v in sorted(self.languages.items(), key=lambda t: -t[1])[:6])
        head = f"REPO MAP: {self.total_files} files, languages: {langs or 'n/a'}"
        if self.truncated:
            head += " (TRUNCATED: large repo, analysis capped; use search/symbols tools)"
        sections.append(head)
        if self.commands:
            sections.append("COMMANDS: " + "; ".join(f"{k}={v}" for k, v in self.commands.items()))
        if self.frameworks:
            sections.append("FRAMEWORKS: " + ", ".join(self.frameworks))
        if self.entrypoints:
            sections.append("ENTRYPOINTS: " + ", ".join(self.entrypoints[:10]))
        if self.tree_summary:
            sections.append("TREE:\n" + self.tree_summary)
        if self.cycles:
            sections.append("IMPORT CYCLES: " + " | ".join(" -> ".join(c) for c in self.cycles[:3]))
        hs = self.hotspots(5)
        sections.append("HOTSPOTS: largest " + ", ".join(f"{p}({n}l)" for p, n in hs["largest_files"]) +
                        "; complex " + ", ".join(f"{p}(cc{n})" for p, n in hs["most_complex_functions"][:4]))
        if self.tests:
            sections.append(f"TESTS ({len(self.tests)}): " + ", ".join(self.tests[:12]) +
                            (" ..." if len(self.tests) > 12 else ""))
        by_file = defaultdict(list)
        for s in self.symbols:
            if s.kind != "method" and not self.files[s.path].is_test:
                by_file[s.path].append(s)
        lines = []
        for path in sorted(by_file, key=lambda p: (-len(by_file[p]), p)):
            names = ", ".join(f"{s.name}" for s in by_file[path][:8])
            lines.append(f"  {path}: {names}{' ...' if len(by_file[path]) > 8 else ''}")
        if lines:
            sections.append("SYMBOLS:\n" + "\n".join(lines))
        out, used = [], 0
        for sec in sections:
            if used + len(sec) + 1 > max_chars:
                room = max_chars - used - 20
                if room > 120:
                    out.append(sec[:room] + "\n...[truncated]")
                break
            out.append(sec)
            used += len(sec) + 1
        return "\n".join(out)

    def slice_for(self, scope_files: list[str], budget_chars: int = 4000) -> str:
        """Sparse context for a unit: its files' symbols, imports, importers, related tests, then neighbours."""
        parts: list[str] = []
        seen: set[str] = set()

        def describe(path: str, detail: bool) -> str:
            f = self.files.get(path)
            if not f:
                return f"{path} (not in map)"
            row = f"{path} [{f.lang}, {f.lines} lines{', test' if f.is_test else ''}]"
            syms = self.symbols_in(path)
            if syms:
                cap = 40 if detail else 8
                row += "\n" + "\n".join(f"    {s.kind} {s.signature or s.name} @L{s.line}" for s in syms[:cap])
                if len(syms) > cap:
                    row += f"\n    ... {len(syms) - cap} more"
            if detail:
                imps = self.import_graph.get(path, [])
                if imps:
                    row += "\n    imports: " + ", ".join(imps[:12])
                users = self.importers_of(path)
                if users:
                    row += "\n    imported by: " + ", ".join(users[:12])
            return row

        for p in scope_files:
            seen.add(p)
            parts.append(describe(p, True))
        tests = self.tests_for(scope_files)
        if tests:
            parts.append("RELATED TESTS: " + ", ".join(tests[:15]))
        neighbours: list[str] = []
        for p in scope_files:
            neighbours += self.import_graph.get(p, []) + self.importers_of(p)
        for p in neighbours:
            if p not in seen:
                seen.add(p)
                parts.append(describe(p, False))
        out, used = [], 0
        for part in parts:
            if used + len(part) + 1 > budget_chars:
                out.append("...[slice truncated]")
                break
            out.append(part)
            used += len(part) + 1
        return "\n".join(out)


# ---- skipping -------------------------------------------------------------------------------------------

def _skip_reason(path: str, text: str) -> str | None:
    p = PurePosixPath(path)
    if any(part in VENDOR_DIRS for part in p.parts[:-1]):
        return "vendor"
    if p.suffix.lower() in BINARY_EXT or "\x00" in text[:4096]:
        return "binary"
    if p.name in LOCK_FILES:
        return "lock"
    if p.name.endswith((".min.js", ".min.css", ".map", ".pb.go", "_pb2.py", "_pb2_grpc.py", ".generated.ts")):
        return "generated"
    head = text[:400]
    if any(m in head for m in GENERATED_MARKERS):
        return "generated"
    return None


# ---- python analysis ------------------------------------------------------------------------------------

_BRANCH = (ast.If, ast.For, ast.AsyncFor, ast.While, ast.ExceptHandler, ast.IfExp, ast.Assert)


def py_complexity(node: ast.AST) -> int:
    c = 1
    for n in ast.walk(node):
        if isinstance(n, _BRANCH):
            c += 1
        elif isinstance(n, ast.BoolOp):
            c += len(n.values) - 1
        elif isinstance(n, ast.comprehension):
            c += 1 + len(n.ifs)
        elif isinstance(n, ast.Match):  # type: ignore[attr-defined]
            c += len(n.cases)
    return c


def _py_sig(node: ast.AST) -> str:
    try:
        a = ast.unparse(node.args)  # type: ignore[attr-defined]
        ret = f" -> {ast.unparse(node.returns)}" if getattr(node, "returns", None) else ""  # type: ignore[attr-defined]
        return f"{node.name}({a}){ret}"  # type: ignore[attr-defined]
    except Exception:
        return getattr(node, "name", "?")


def analyse_python(path: str, text: str) -> tuple[list[Symbol], list[FuncMetric], list[str]]:
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError, RecursionError):
        return [], [], []
    syms: list[Symbol] = []
    funcs: list[FuncMetric] = []
    imports: list[str] = []
    exports: set[str] | None = None
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets):
            try:
                exports = {e for e in ast.literal_eval(node.value)}
            except Exception:
                exports = None

    def add_func(node: ast.AST, prefix: str, kind: str) -> None:
        end = getattr(node, "end_lineno", node.lineno) or node.lineno  # type: ignore[attr-defined]
        name = f"{prefix}{node.name}"  # type: ignore[attr-defined]
        funcs.append(FuncMetric(name, node.lineno, end - node.lineno + 1, py_complexity(node)))  # type: ignore[attr-defined]
        pub = not node.name.startswith("_") or node.name.startswith("__")  # type: ignore[attr-defined]
        syms.append(Symbol(name, kind, path, node.lineno, f"{prefix}{_py_sig(node)}", pub))  # type: ignore[attr-defined]

    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            add_func(node, "", "function")
        elif isinstance(node, ast.ClassDef):
            bases = ", ".join(ast.unparse(b) for b in node.bases)
            syms.append(Symbol(node.name, "class", path, node.lineno, f"{node.name}({bases})",
                               not node.name.startswith("_")))
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    add_func(sub, node.name + ".", "method")
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id.isupper():
                    syms.append(Symbol(t.id, "const", path, node.lineno, t.id, True))
    if exports is not None:
        for s in syms:
            s.exported = s.name.split(".")[0] in exports
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imports += [a.name for a in node.names]
        elif isinstance(node, ast.ImportFrom):
            mod = ("." * node.level) + (node.module or "")
            if node.module:  # `from . import x` depends on the submodule x, not on the package __init__
                imports.append(mod)
            imports += [f"{mod}.{a.name}" if not mod.endswith(".") else f"{mod}{a.name}" for a in node.names]
    return syms, funcs, imports


# ---- JS / TS analysis -----------------------------------------------------------------------------------

_JS_DECL = re.compile(
    r"^(?P<exp>export\s+(?:default\s+)?)?(?:declare\s+)?(?:(?P<async>async\s+)?function\*?\s+(?P<fn>[A-Za-z_$][\w$]*)"
    r"|(?:abstract\s+)?class\s+(?P<cls>[A-Za-z_$][\w$]*)"
    r"|interface\s+(?P<iface>[A-Za-z_$][\w$]*)"
    r"|type\s+(?P<type>[A-Za-z_$][\w$]*)\s*[<=]"
    r"|enum\s+(?P<enum>[A-Za-z_$][\w$]*)"
    r"|(?:const|let|var)\s+(?P<var>[A-Za-z_$][\w$]*)\s*(?::[^=]+)?=\s*(?P<arrow>(?:async\s*)?(?:\([^)]*\)|[A-Za-z_$][\w$]*)\s*(?::[^=]+)?=>|(?:async\s+)?function\b)?)",
    re.M)
_JS_IMPORT = re.compile(
    r"""(?:import\s+(?:[^'"]*?\s+from\s+)?|export\s+[^'"]*?\s+from\s+|require\(\s*|import\(\s*)['"]([^'"]+)['"]""")
_JS_BRANCH = re.compile(r"\b(?:if|for|while|case|catch)\b|&&|\|\||\?\?|\?(?![.?:])")


def _strip_js_noise(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.S)
    text = re.sub(r"(?m)(?<![:'\"\w])//.*$", "", text)
    return text


def _brace_end(lines: list[str], start: int) -> int:
    depth, seen = 0, False
    for i in range(start, min(len(lines), start + 800)):
        for ch in re.sub(r"""(['"`])(?:\\.|(?!\1).)*\1""", "", lines[i]):
            if ch == "{":
                depth += 1
                seen = True
            elif ch == "}":
                depth -= 1
        if seen and depth <= 0:
            return i
        if not seen and i > start + 2 and lines[i].rstrip().endswith((";", ")")):
            return i
    return start


def analyse_js(path: str, text: str) -> tuple[list[Symbol], list[FuncMetric], list[str]]:
    clean = _strip_js_noise(text)
    lines = clean.splitlines()
    syms: list[Symbol] = []
    funcs: list[FuncMetric] = []
    for m in _JS_DECL.finditer(clean):
        line = clean.count("\n", 0, m.start()) + 1
        exported = bool(m.group("exp"))
        if m.group("fn"):
            kind, name = "function", m.group("fn")
        elif m.group("cls"):
            kind, name = "class", m.group("cls")
        elif m.group("iface"):
            kind, name = "interface", m.group("iface")
        elif m.group("type"):
            kind, name = "type", m.group("type")
        elif m.group("enum"):
            kind, name = "enum", m.group("enum")
        elif m.group("var"):
            name = m.group("var")
            kind = ("component" if name[:1].isupper() else "function") if m.group("arrow") else "const"
            if kind == "const" and not exported:
                continue
        else:
            continue
        sig_line = lines[line - 1].strip()[:140] if line - 1 < len(lines) else name
        syms.append(Symbol(name, kind, path, line, sig_line.rstrip("{").strip(), exported))
        if kind in ("function", "component", "class"):
            end = _brace_end(lines, line - 1) + 1
            body = "\n".join(lines[line - 1:end])
            funcs.append(FuncMetric(name, line, end - line + 1, 1 + len(_JS_BRANCH.findall(body))))
    exp_list = re.findall(r"export\s*\{([^}]*)\}", clean)
    listed = {x.split(" as ")[-1].strip() for blk in exp_list for x in blk.split(",") if x.strip()}
    for s in syms:
        if s.name in listed:
            s.exported = True
    imports = _JS_IMPORT.findall(clean)
    return syms, funcs, imports


# ---- Go analysis ----------------------------------------------------------------------------------------

_GO_FUNC = re.compile(r"^func\s+(?:\((?P<recv>[^)]*)\)\s*)?(?P<name>[A-Za-z_]\w*)\s*(?P<rest>\([^{]*)", re.M)
_GO_TYPE = re.compile(r"^type\s+([A-Za-z_]\w*)\s+(struct|interface)\b", re.M)
_GO_IMPORT_BLOCK = re.compile(r"^import\s*\((.*?)^\)", re.M | re.S)
_GO_IMPORT_ONE = re.compile(r'^import\s+(?:\w+\s+)?"([^"]+)"', re.M)
_GO_BRANCH = re.compile(r"\b(?:if|for|case|select)\b|&&|\|\|")


def analyse_go(path: str, text: str) -> tuple[list[Symbol], list[FuncMetric], list[str]]:
    lines = text.splitlines()
    syms: list[Symbol] = []
    funcs: list[FuncMetric] = []
    for m in _GO_FUNC.finditer(text):
        line = text.count("\n", 0, m.start()) + 1
        name = m.group("name")
        recv = (m.group("recv") or "").split()
        rtype = recv[-1].lstrip("*") if recv else ""
        full = f"{rtype}.{name}" if rtype else name
        syms.append(Symbol(full, "method" if rtype else "function", path, line,
                           lines[line - 1].rstrip("{ ").strip()[:140], name[:1].isupper()))
        end = _brace_end(lines, line - 1) + 1
        funcs.append(FuncMetric(full, line, end - line + 1,
                                1 + len(_GO_BRANCH.findall("\n".join(lines[line - 1:end])))))
    for m in _GO_TYPE.finditer(text):
        syms.append(Symbol(m.group(1), "type" if m.group(2) == "struct" else "interface", path,
                           text.count("\n", 0, m.start()) + 1, f"type {m.group(1)} {m.group(2)}", m.group(1)[:1].isupper()))
    imports = [q for blk in _GO_IMPORT_BLOCK.findall(text) for q in re.findall(r'"([^"]+)"', blk)]
    imports += _GO_IMPORT_ONE.findall(text)
    return syms, funcs, imports


# ---- command / framework detection ----------------------------------------------------------------------

def detect_commands(files: dict[str, str]) -> tuple[dict[str, str], list[str], str]:
    cmds: dict[str, str] = {}
    frameworks: list[str] = []
    primary = "unknown"
    info = detect(files)
    if info["language"] == "python":
        primary = "python"
        cmds["test"] = info["test_command"]
        frameworks.append(info["framework"])
        pyproj = files.get("pyproject.toml", "")
        if "[tool.ruff" in pyproj or "ruff.toml" in files or ".ruff.toml" in files or "ruff" in files.get("requirements-dev.txt", ""):
            cmds["lint"] = "python -m ruff check ."
        if "mypy.ini" in files or "[tool.mypy" in pyproj or "[mypy]" in files.get("setup.cfg", ""):
            cmds["typecheck"] = "python -m mypy ."
        if "requirements.txt" in files:
            cmds["install"] = "python -m pip install -r requirements.txt"
    pkg_text = files.get("package.json")
    if pkg_text:
        try:
            pkg = json.loads(pkg_text)
        except ValueError:
            pkg = {}
        scripts = pkg.get("scripts", {}) if isinstance(pkg.get("scripts"), dict) else {}
        deps = {**(pkg.get("dependencies") or {}), **(pkg.get("devDependencies") or {})}
        pm = "pnpm" if "pnpm-lock.yaml" in files else "yarn" if "yarn.lock" in files else "npm"
        if primary == "unknown":
            primary = "typescript" if ("typescript" in deps or "tsconfig.json" in files) else "javascript"
        cmds["install"] = f"{pm} ci" if pm == "npm" and "package-lock.json" in files else f"{pm} install"
        run = "" if pm == "yarn" else "run "
        for key, names in (("build", ["build"]), ("test", ["test"]), ("lint", ["lint"]),
                           ("typecheck", ["typecheck", "type-check", "tsc"]), ("dev", ["dev", "start"])):
            for n in names:
                if n in scripts:
                    cmds[key] = f"{pm} test" if key == "test" and pm == "npm" else f"{pm} {run}{n}"
                    break
        if "typecheck" not in cmds and ("tsconfig.json" in files and "typescript" in deps):
            cmds["typecheck"] = "npx tsc --noEmit"
        for fw in ("vite", "next", "vitest", "jest", "react", "vue", "svelte", "express", "mocha", "playwright", "eslint"):
            if fw in deps or f"{fw}.config.js" in files or f"{fw}.config.ts" in files:
                frameworks.append(fw)
        if info["language"] != "python" and "test" not in cmds and "vitest" in deps:
            cmds["test"] = "npx vitest run"
    if "go.mod" in files:
        if primary == "unknown":
            primary = "go"
        cmds.setdefault("build", "go build ./...")
        cmds.setdefault("test", "go test ./...")
        cmds.setdefault("lint", "go vet ./...")
        frameworks.append("go")
    if "Cargo.toml" in files:
        cmds.setdefault("build", "cargo build")
        cmds.setdefault("test", "cargo test")
        frameworks.append("cargo")
    if "Makefile" in files and "test" not in cmds and re.search(r"^test:", files["Makefile"], re.M):
        cmds["test"] = "make test"
    return cmds, list(dict.fromkeys(frameworks)), primary


# ---- graph helpers --------------------------------------------------------------------------------------

def find_cycles(graph: dict[str, list[str]], limit: int = 20) -> list[list[str]]:
    """Strongly connected components of size > 1 (iterative Tarjan), each reported as one cycle path."""
    index: dict[str, int] = {}
    low: dict[str, int] = {}
    on: set[str] = set()
    stack: list[str] = []
    cycles: list[list[str]] = []
    counter = 0
    for root in sorted(graph):
        if root in index:
            continue
        work = [(root, iter(sorted(graph.get(root, []))))]
        index[root] = low[root] = counter
        counter += 1
        stack.append(root)
        on.add(root)
        while work:
            node, it = work[-1]
            advanced = False
            for nxt in it:
                if nxt not in graph:
                    continue
                if nxt not in index:
                    index[nxt] = low[nxt] = counter
                    counter += 1
                    stack.append(nxt)
                    on.add(nxt)
                    work.append((nxt, iter(sorted(graph.get(nxt, [])))))
                    advanced = True
                    break
                if nxt in on:
                    low[node] = min(low[node], index[nxt])
            if advanced:
                continue
            work.pop()
            if work:
                low[work[-1][0]] = min(low[work[-1][0]], low[node])
            if low[node] == index[node]:
                comp = []
                while True:
                    w = stack.pop()
                    on.discard(w)
                    comp.append(w)
                    if w == node:
                        break
                if len(comp) > 1 or node in graph.get(node, []):
                    cycles.append(sorted(comp) + [sorted(comp)[0]])
                    if len(cycles) >= limit:
                        return cycles
    return cycles


def _py_modules(paths: list[str]) -> dict[str, str]:
    mods: dict[str, str] = {}
    for p in paths:
        if not p.endswith(".py"):
            continue
        parts = p[:-3].split("/")
        if parts[-1] == "__init__":
            parts = parts[:-1]
        if not parts:
            continue
        for i in range(min(3, len(parts))):  # also register with leading dirs stripped (src/, lib/ layouts)
            mods.setdefault(".".join(parts[i:]), p)
    return mods


def _resolve_py(raw: str, src: str, mods: dict[str, str]) -> str | None:
    if raw.startswith("."):
        level = len(raw) - len(raw.lstrip("."))
        base = src.split("/")[:-1]
        if level > 1:
            base = base[: len(base) - (level - 1)] if len(base) >= level - 1 else []
        rest = raw.lstrip(".")
        cand = ".".join(base + ([rest] if rest else []))
        for key in (cand,):
            if key in mods:
                return mods[key]
        # relative to a stripped root (src/pkg/x.py -> module pkg.x)
        for k, v in mods.items():
            if v.startswith("/".join(base)) and k.endswith(rest) and rest:
                return v
        return None
    return mods.get(raw)


def _resolve_js(raw: str, src: str, paths: set[str]) -> str | None:
    if not raw.startswith("."):
        if raw.startswith(("@/", "~/")):
            raw = "./src/" + raw[2:]
            base = ""
        else:
            return None
    else:
        base = posixpath.dirname(src)
    cand = posixpath.normpath(posixpath.join(base, raw)) if base else posixpath.normpath(raw)
    options = [cand] + [cand + e for e in JS_EXT] + [f"{cand}/index{e}" for e in JS_EXT]
    stem = re.sub(r"\.(js|jsx|mjs|cjs)$", "", cand)
    options += [stem + e for e in (".ts", ".tsx")]
    for o in options:
        if o in paths:
            return o
    return None


def _resolve_go(raw: str, module: str, dir_index: dict[str, list[str]]) -> list[str]:
    if module and raw.startswith(module):
        rel = raw[len(module):].lstrip("/")
        return dir_index.get(rel or ".", [])[:20]
    return []


def _test_target_names(path: str) -> list[str]:
    p = PurePosixPath(path)
    n = p.name
    stems = []
    for rx in (r"^test_(.+)\.py$", r"^(.+)_test\.py$", r"^(.+)_test\.go$", r"^(.+)\.(?:test|spec)\.(?:[jt]sx?|mjs)$",
               r"^(.+)Test\.java$", r"^test(.+)\.py$"):
        m = re.match(rx, n)
        if m:
            stems.append(m.group(1))
    return stems


def build_repo_map(files: dict[str, str], *, max_files: int = MAX_ANALYSED_FILES) -> RepoMap:
    rm = RepoMap(total_files=len(files))
    skipped: Counter[str] = Counter()
    keep: list[str] = []
    for path in sorted(files):
        reason = _skip_reason(path, files[path])
        if reason:
            skipped[reason] += 1
            continue
        keep.append(path)
    if len(keep) > max_files:
        # keep shallow + code-language files first so the map stays useful when truncated
        keep.sort(key=lambda p: (LANG_BY_EXT.get(PurePosixPath(p).suffix.lower()) not in CODE_LANGS,
                                 p.count("/"), p))
        skipped["cap"] += len(keep) - max_files
        keep = sorted(keep[:max_files])
        rm.truncated = True
    rm.skipped = dict(skipped)

    commands, frameworks, primary = detect_commands(files)
    rm.commands, rm.frameworks, rm.primary_language = commands, frameworks, primary
    lang_lines: Counter[str] = Counter()
    raw_imports: dict[str, list[str]] = {}
    for path in keep:
        text = files[path]
        lang = LANG_BY_EXT.get(PurePosixPath(path).suffix.lower(), "other")
        n_lines = text.count("\n") + (1 if text and not text.endswith("\n") else 0)
        info = FileInfo(path, lang, n_lines, len(text), is_test=is_test_path(path))
        lang_lines[lang] += n_lines
        if lang in ("python", "javascript", "typescript", "go") and len(text) <= MAX_ANALYSED_BYTES:
            fn = analyse_python if lang == "python" else analyse_go if lang == "go" else analyse_js
            syms, funcs, imps = fn(path, text)
            info.parsed = True
            info.functions = funcs
            rm.symbols += syms
            raw_imports[path] = imps
            info.imports_raw = imps[:200]
        elif lang in ("vue", "svelte") and len(text) <= MAX_ANALYSED_BYTES:
            raw_imports[path] = _JS_IMPORT.findall(text)
        rm.files[path] = info
    rm.languages = dict(lang_lines)
    if primary == "unknown" and lang_lines:
        code = [(n, l) for l, n in lang_lines.items() if l in CODE_LANGS]
        if code:
            rm.primary_language = max(code)[1]

    # import graph
    paths = set(rm.files)
    mods = _py_modules(list(paths))
    module = ""
    gomod = files.get("go.mod", "")
    m = re.search(r"^module\s+(\S+)", gomod, re.M)
    if m:
        module = m.group(1)
    dir_index: dict[str, list[str]] = defaultdict(list)
    for p in paths:
        if p.endswith(".go") and not p.endswith("_test.go"):
            dir_index[posixpath.dirname(p) or "."].append(p)
    graph: dict[str, list[str]] = {}
    for path, raws in raw_imports.items():
        lang = rm.files[path].lang
        out: list[str] = []
        for raw in raws:
            if lang == "python":
                tgt = _resolve_py(raw, path, mods)
                targets = [tgt] if tgt else []
            elif lang == "go":
                targets = _resolve_go(raw, module, dir_index)
            else:
                tgt = _resolve_js(raw, path, paths)
                targets = [tgt] if tgt else []
            for t in targets:
                if t != path and t not in out:
                    out.append(t)
        graph[path] = out
    rm.import_graph = graph
    importers: dict[str, list[str]] = defaultdict(list)
    for src, dsts in graph.items():
        for d in dsts:
            importers[d].append(src)
    rm._importers = {k: sorted(v) for k, v in importers.items()}
    code_graph = {p: [d for d in ds if not rm.files[p].is_test] for p, ds in graph.items() if not rm.files[p].is_test}
    rm.cycles = find_cycles(code_graph)

    # symbols index
    by_path: dict[str, list[Symbol]] = defaultdict(list)
    for s in rm.symbols:
        by_path[s.path].append(s)
    rm._by_path = dict(by_path)

    # tests & test map
    rm.tests = sorted(p for p, f in rm.files.items() if f.is_test and f.lang in CODE_LANGS)
    srcs_by_stem: dict[str, list[str]] = defaultdict(list)
    for p, f in rm.files.items():
        if f.lang in CODE_LANGS and not f.is_test:
            srcs_by_stem[PurePosixPath(p).stem.lower()].append(p)
    for t in rm.tests:
        covered: list[str] = []
        for stem in _test_target_names(t):
            covered += srcs_by_stem.get(stem.lower(), [])
        covered += [d for d in graph.get(t, []) if not rm.files[d].is_test]
        rm.test_map[t] = sorted(dict.fromkeys(covered))

    # entrypoints
    eps: list[str] = []
    for p, f in rm.files.items():
        name = PurePosixPath(p).name
        if f.lang == "python" and (name in ("__main__.py", "main.py", "app.py", "manage.py", "wsgi.py", "asgi.py", "cli.py")
                                   or re.search(r'if __name__\s*==\s*[\'"]__main__[\'"]', files[p])) and not f.is_test:
            eps.append(p)
        elif f.lang in ("javascript", "typescript") and re.match(r"^(index|main|server|app)\.(?:[jt]sx?|mjs)$", name) \
                and p.count("/") <= 2 and not f.is_test:
            eps.append(p)
        elif f.lang == "go" and re.search(r"^package main\b", files[p], re.M) and not f.is_test:
            eps.append(p)
        elif name == "index.html" and p.count("/") <= 1:
            eps.append(p)
    pkg_text = files.get("package.json")
    if pkg_text:
        try:
            pkg = json.loads(pkg_text)
            for key in ("main", "module"):
                v = pkg.get(key)
                if isinstance(v, str) and v.lstrip("./") in rm.files:
                    eps.append(v.lstrip("./"))
        except ValueError:
            pass
    rm.entrypoints = sorted(dict.fromkeys(eps))[:30]

    rm.tree_summary = _tree_summary(rm)
    return rm


def _tree_summary(rm: RepoMap, max_lines: int = 28) -> str:
    counts: Counter[str] = Counter()
    for p in rm.files:
        parts = p.split("/")
        counts["/".join(parts[:2]) + "/" if len(parts) > 2 else (parts[0] + "/" if len(parts) == 2 else "(root)")] += 1
    rows = [f"  {d} ({n} files)" for d, n in sorted(counts.items(), key=lambda t: (-t[1], t[0]))[:max_lines]]
    return "\n".join(sorted(rows))
